"""Автотест зчитування реквізитів на синтетичному тексті (вигадані дані, схожа розкладка 1С-форми)."""
import docinfo

TEXT = """Видаткова накладна № 277 від 23 вересня 2026 р.
(Продаж покупцю)
Постачальник Фізична особа - підприємець Петренко Іван Іванович, ІПН 1234567890, ДРФО
1234567890, р/р UA213223130000026007233566001 у банку ПАТ "БАНК", м.Київ, 21021, м.
Вінниця, вул. Тестова, будинок 1, тел.: +380 (97) 000-00-00
Покупець Фізична особа-підприємець Сидоренко Олег Васильович, 23100, Вінницька обл., м. Жмеринка, вул.
Київська, будинок 2
Договір: № 82 від 01.01.2024
Склад: Основний склад (Основний підрозділ)
Адреса
доставки: 23100, Вінницька обл., м. Жмеринка, вул. Київська, будинок 2
№ Товари (Послуги) Кількість Ціна Сума
1 Принтер 1 шт 3 600,00 3 600,00
Разом: 22 500,00
Всього найменувань 2, на суму 22 500,00 грн.
"""

info = dict(docinfo.parse_header_text(TEXT, "Накладна № НФ-277 від 23.09.2026.pdf"))
for k, v in info.items():
    print(f"{k}: {v}")

assert info["Документ"] == "Видаткова накладна"
assert info["Номер"] == "277" and info["Дата"] == "23.09.2026"
assert info["Номер у назві файлу"] == "НФ-277" and "Дата у назві файлу" not in info
assert info["Постачальник"] == "Фізична особа - підприємець Петренко Іван Іванович"
assert info["Постачальник: код"] == "ІПН 1234567890"
assert info["Постачальник: IBAN"] == "UA213223130000026007233566001"
assert info["Покупець"] == "Фізична особа-підприємець Сидоренко Олег Васильович"
assert "Покупець: код" not in info
assert info["Договір"] == "№ 82 від 01.01.2024"
assert info["Склад"] == "Основний склад (Основний підрозділ)"
assert info["Адреса доставки"].startswith("23100, Вінницька обл.")
assert info["Кількість найменувань"] == "2" and info["Разом"] == "22 500,00"

assert docinfo.parse_date("1 жовтня 2026 р.") == "01.10.2026"
assert docinfo.parse_date("5 января 2025 года") == "05.01.2025"
assert docinfo.parse_date("3/4/2026") == "03.04.2026"
assert docinfo.parse_date("без дати") is None

assert docinfo.parse_header_text("Просто текст без реквізитів") == []
# вікно реквізитів і копіювання в буфер обміну
from app import App

app = App()
app._set_info(list(info.items()), show=True)
assert app._info_win is not None and app._info_win.winfo_exists()
assert str(app.info_btn.cget("state")) == "normal"
app._copy("Номер", info["Номер"])
assert app.clipboard_get() == "277"
app._copy_all()
copied = app.clipboard_get().split("\n")
assert copied[0] == "Документ\tВидаткова накладна" and len(copied) == len(info)
app._set_info([], show=False)
assert app._info_win is None and str(app.info_btn.cget("state")) == "disabled"
app.destroy()
print("ВСІ ПЕРЕВІРКИ РЕКВІЗИТІВ ПРОЙДЕНО")
